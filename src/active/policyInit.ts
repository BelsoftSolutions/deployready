/**
 * `deployready policy init [path]`: draft an authorization policy from the
 * discovered routes and write it into `.deployready.json` for the user to
 * review. The draft is marked `"draft": true`, and the engine refuses to run a
 * draft: every heuristic access level has to be confirmed by a human first.
 */
import * as fs from 'fs/promises';
import * as path from 'path';
import type { Route } from '../types';
import { draftPolicy } from './policy';
import { PROJECT_CONFIG_FILE } from './projectConfig';

export interface PolicyInitOptions {
  /** Replace an existing active.policy. */
  force?: boolean;
  /** Do not write; return the JSON only. */
  print?: boolean;
  /** Fixed timestamp (tests). */
  now?: Date;
}

export interface PolicyInitResult {
  file: string;
  written: boolean;
  json: string;
  resources: number;
  excluded: number;
}

const EXAMPLE_IDENTITIES = [
  { _comment: 'Anonymous visitor: no credentials. Always tested.', name: 'anonymous', role: 'anonymous' },
  { name: 'user', role: 'user', tenant: 'tenant-a', tokenEnv: 'DR_USER_TOKEN', params: { userId: '<your test user id>' }, objects: {} },
  { name: 'user2', role: 'user', tenant: 'tenant-a', tokenEnv: 'DR_USER2_TOKEN', params: { userId: '<second test user id>' }, objects: {} },
  { name: 'admin', role: 'admin', tenant: 'tenant-a', tokenEnv: 'DR_ADMIN_TOKEN' },
  { name: 'other-tenant', role: 'user', tenant: 'tenant-b', tokenEnv: 'DR_OTHER_TENANT_TOKEN', params: { userId: '<user id in another tenant>' }, objects: {} },
];

/** Build the draft `active.policy` object (pure). */
export function buildDraftPolicy(routes: Route[], now = new Date()): Record<string, unknown> {
  const d = draftPolicy(routes);
  return {
    draft: true,
    _comment: `DRAFT generated by \`deployready policy init\` on ${now.toISOString().slice(0, 10)} from ${routes.length} discovered route(s). Every access level below is a GUESS from the route name. Review each resource, fix the levels (none | read | own | manage), then set "draft": false. DeployReady refuses to test a draft.`,
    roles: ['anonymous', 'user', 'admin'],
    resources: d.resources.map((r) => ({ name: r.name, _why: r.why, routes: r.routes, access: r.access, tenantScoped: r.tenantScoped })),
    ...(d.excluded.length ? { _excluded: d.excluded } : {}),
    ...(d.graphqlEndpoint ? { graphql: { endpoint: d.graphqlEndpoint, introspection: 'deny', queries: [] } } : {}),
  };
}

export async function initPolicy(projectPath: string, routes: Route[], opts: PolicyInitOptions = {}): Promise<PolicyInitResult> {
  const file = path.join(projectPath, PROJECT_CONFIG_FILE);
  let existing: Record<string, unknown> = {};
  let raw: string | null = null;
  try {
    raw = await fs.readFile(file, 'utf8');
  } catch {
    raw = null;
  }
  if (raw !== null) {
    try {
      const parsed = JSON.parse(raw) as unknown;
      if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) throw new Error('not a JSON object');
      existing = parsed as Record<string, unknown>;
    } catch (err) {
      throw new Error(`${PROJECT_CONFIG_FILE} exists but is not a valid JSON object (${(err as Error).message}); fix it first, nothing was written.`);
    }
  }
  const active = (typeof existing.active === 'object' && existing.active !== null ? existing.active : {}) as Record<string, unknown>;
  if (active.policy !== undefined && !opts.force && !opts.print) {
    throw new Error(`${PROJECT_CONFIG_FILE} already has an active.policy. Re-run with --force to replace it, or --print to see a fresh draft.`);
  }
  const policy = buildDraftPolicy(routes, opts.now);
  const next = {
    ...existing,
    active: {
      ...active,
      ...(Array.isArray(active.identities) && active.identities.length ? {} : { identities: EXAMPLE_IDENTITIES }),
      policy,
    },
  };
  const json = `${JSON.stringify(next, null, 2)}\n`;
  const resources = (policy.resources as unknown[]).length;
  const excluded = Array.isArray(policy._excluded) ? policy._excluded.length : 0;
  if (opts.print) return { file, written: false, json, resources, excluded };
  const tmp = `${file}.tmp-${process.pid}`;
  await fs.writeFile(tmp, json, { mode: 0o644 });
  await fs.rename(tmp, file);
  return { file, written: true, json, resources, excluded };
}
