import * as fs from 'fs/promises';
import * as os from 'os';
import * as path from 'path';
import { ExportManager } from '../src/ui/ExportManager';
import { HtmlReporter } from '../src/ui/HtmlReporter';
import { FixWalker } from '../src/ui/FixWalker';
import { PlatformRecommender } from '../src/deploy/PlatformRecommender';
import { makeFinding } from '../src/utils/finding';
import type { Finding, ScanReport } from '../src/types';

function f(over: Partial<Omit<Finding, 'id'>> = {}): Finding {
  return makeFinding({
    rule: 'r', title: 'A finding', severity: 'warning', category: 'security', source: 'static',
    description: 'desc', recommendation: 'do the fix', file: 'src/a.js', line: 7, ...over,
  } as Omit<Finding, 'id'>);
}

function report(findings: Finding[] = [], over: Partial<ScanReport> = {}): ScanReport {
  const sev = (s: string) => findings.filter((x) => x.severity === s && x.source !== 'ai' && !x.unverified).length;
  return {
    target: '/app', startedAt: '2026-06-06T00:00:00Z', finishedAt: '', version: '9.9.9',
    stack: { stack: 'express', language: 'javascript', evidence: [] },
    graph: { root: '/app', stack: { stack: 'express', language: 'javascript', evidence: [] }, entryPoints: [], modules: [], routes: [], fileCount: 3 },
    findings, score: 90, summary: { critical: sev('critical'), warning: sev('warning'), info: sev('info'), total: findings.length },
    ...over,
  } as ScanReport;
}

describe('ExportManager.toMarkdown', () => {
  it('renders header fields, version footer and no sections for an empty report', () => {
    const md = ExportManager.toMarkdown(report());
    expect(md).toContain('# DeployReady Report');
    expect(md).toContain('- **Target:** `/app`');
    expect(md).toContain('- **Score:** 90/100');
    expect(md).toContain('- **Stack:** express (javascript)');
    expect(md).toContain('_Generated by DeployReady v9.9.9_');
    expect(md).not.toContain('## CRITICAL');
    expect(md).not.toContain('## WARNING');
    expect(md).not.toContain('AI SUGGESTIONS');
    expect(md).not.toContain('AI Summary');
  });

  it('groups findings by severity in critical, warning, info order', () => {
    const md = ExportManager.toMarkdown(report([
      f({ severity: 'info', title: 'I1', rule: 'i' }),
      f({ severity: 'critical', title: 'C1', rule: 'c' }),
      f({ severity: 'warning', title: 'W1', rule: 'w' }),
    ]));
    const c = md.indexOf('## CRITICAL (1)');
    const w = md.indexOf('## WARNING (1)');
    const i = md.indexOf('## INFO (1)');
    expect(c).toBeGreaterThan(-1);
    expect(w).toBeGreaterThan(c);
    expect(i).toBeGreaterThan(w);
  });

  it('shows the AI summary and keeps AI suggestions out of the scored severity groups', () => {
    const ai = f({ source: 'ai', severity: 'critical', title: 'AI guess', rule: 'ai1' });
    const md = ExportManager.toMarkdown(report([ai], { aiSummary: 'Looks risky.' }));
    expect(md).toContain('## AI Summary (unverified)');
    expect(md).toContain('Looks risky.');
    expect(md).toContain('- **AI suggestions:** 1 (unverified, not scored)');
    expect(md).toContain('## AI SUGGESTIONS — unverified, not scored (1)');
    expect(md).not.toContain('## CRITICAL');
    expect(md).toContain('- **Source:** ai (unverified)');
  });

  it('treats an explicit unverified flag like an AI suggestion even for a static source', () => {
    const md = ExportManager.toMarkdown(report([f({ unverified: true, title: 'Flagged' })]));
    expect(md).toContain('## AI SUGGESTIONS');
    expect(md).not.toContain('## WARNING');
  });

  it('prefers endpoint over file:line, falls back to file, then to a dash', () => {
    const md = ExportManager.toMarkdown(report([
      f({ endpoint: 'GET /users', rule: 'e' }),
      f({ file: 'src/x.ts', line: undefined, rule: 'nl' }),
      f({ file: undefined, line: undefined, endpoint: undefined, rule: 'none' }),
    ]));
    expect(md).toContain('- **Where:** `GET /users`');
    expect(md).toContain('- **Where:** `src/x.ts`');
    expect(md).not.toContain('`src/x.ts:');
    expect(md).toContain('- **Where:** `—`');
  });

  it('includes OWASP, CWE and evidence lines only when present', () => {
    const withAll = ExportManager.toMarkdown(report([f({ owasp: 'A01', cwe: 'CWE-79', evidence: 'x = [REDACTED]' })]));
    expect(withAll).toContain('- **OWASP:** A01');
    expect(withAll).toContain('- **CWE:** CWE-79');
    expect(withAll).toContain('- **Evidence:** `x = [REDACTED]`');
    const bare = ExportManager.toMarkdown(report([f()]));
    expect(bare).not.toContain('**OWASP:**');
    expect(bare).not.toContain('**CWE:**');
    expect(bare).not.toContain('**Evidence:**');
    expect(bare).toContain('- **Fix:** do the fix');
  });
});

describe('ExportManager file output', () => {
  let dir: string;
  beforeEach(async () => { dir = await fs.mkdtemp(path.join(os.tmpdir(), 'dr-export-')); });
  afterEach(async () => { await fs.rm(dir, { recursive: true, force: true }); });

  it('saveMarkdown writes deployready-report.md and returns its path', async () => {
    const file = await ExportManager.saveMarkdown(report([f()]), dir);
    expect(file).toBe(path.join(dir, 'deployready-report.md'));
    const body = await fs.readFile(file, 'utf8');
    expect(body).toBe(ExportManager.toMarkdown(report([f()])));
  });

  it('saveHtml writes deployready-report.html and returns its path', async () => {
    const file = await ExportManager.saveHtml(report([f()]), dir);
    expect(file).toBe(path.join(dir, 'deployready-report.html'));
    const body = await fs.readFile(file, 'utf8');
    expect(body.startsWith('<!DOCTYPE html>')).toBe(true);
  });

  it('rejects when the output directory does not exist', async () => {
    const missing = path.join(dir, 'nope', 'deeper');
    await expect(ExportManager.saveMarkdown(report(), missing)).rejects.toThrow();
    await expect(ExportManager.saveHtml(report(), missing)).rejects.toThrow();
  });

  it('overwrites an existing report file', async () => {
    await fs.writeFile(path.join(dir, 'deployready-report.md'), 'stale', 'utf8');
    const file = await ExportManager.saveMarkdown(report(), dir);
    expect(await fs.readFile(file, 'utf8')).not.toContain('stale');
  });
});

describe('HtmlReporter edge cases', () => {
  afterEach(() => jest.restoreAllMocks());

  it('shows the empty state and no AI/unverified UI for a clean report', () => {
    const html = HtmlReporter.render(report());
    expect(html).toContain('No issues found.');
    expect(html).not.toContain('AI Summary');
    expect(html).not.toContain('data-f="unverified"');
    expect(html).toContain('All (0)');
  });

  it('picks the score colour by threshold', () => {
    expect(HtmlReporter.render(report([], { score: 80 }))).toContain('--c:#00ff88');
    expect(HtmlReporter.render(report([], { score: 79 }))).toContain('--c:#f59e0b');
    expect(HtmlReporter.render(report([], { score: 50 }))).toContain('--c:#f59e0b');
    expect(HtmlReporter.render(report([], { score: 49 }))).toContain('--c:#ef4444');
  });

  it('marks AI findings as UNVERIFIED with their own filter and card', () => {
    const html = HtmlReporter.render(report([f({ source: 'ai', severity: 'critical', title: 'AI guess' })]));
    expect(html).toContain('data-sev="unverified"');
    expect(html).toContain('UNVERIFIED');
    expect(html).toContain('AI suggestions, unverified (1)');
    expect(html).toContain('AI (unverified)');
    expect(html).not.toContain('>CRITICAL<');
  });

  it('escapes every user-controlled field, including target, stack, aiSummary, location, refs and evidence', () => {
    const payload = '<script>alert(1)</script>';
    const evil = f({
      title: payload, description: payload, recommendation: payload, evidence: payload,
      file: payload, line: 1, owasp: payload, cwe: payload, source: 'static',
    });
    const html = HtmlReporter.render(report([evil], {
      target: payload, aiSummary: payload, startedAt: payload, version: payload,
      stack: { stack: payload as never, language: payload as never, evidence: [] },
    }));
    expect(html).not.toContain(payload);
    expect(html).toContain('&lt;script&gt;alert(1)&lt;/script&gt;');
    // The only <script> element is the report's own filter script.
    expect(html.match(/<script>/g)).toHaveLength(1);
  });

  it('escapes quotes so values cannot break out of an attribute', () => {
    const html = HtmlReporter.render(report([f({ title: `"><img src=x onerror=1>`, endpoint: `GET /"x"'y` })]));
    expect(html).not.toContain('"><img');
    expect(html).toContain('&quot;&gt;&lt;img');
    expect(html).toContain('GET /&quot;x&quot;&#39;y');
  });

  it('renders file:line only when a line number is set', () => {
    const html = HtmlReporter.render(report([
      f({ file: 'a.js', line: 12, rule: 'l' }),
      f({ file: 'b.js', line: undefined, rule: 'nl' }),
      f({ file: undefined, line: undefined, rule: 'none' }),
    ]));
    expect(html).toContain('<code>a.js:12</code>');
    expect(html).toContain('<code>b.js</code>');
    expect(html.match(/<code>/g)).toHaveLength(2);
  });

  it('omits the deployment section instead of failing when the recommender throws', () => {
    jest.spyOn(PlatformRecommender, 'recommend').mockImplementation(() => { throw new Error('boom'); });
    const html = HtmlReporter.render(report([f()]));
    expect(html).not.toContain('Recommended deployment');
    expect(html).toContain('A finding');
  });

  it('renders split recommendation, alternatives, free badge and notes from the recommender', () => {
    const pick = (name: string, free: boolean) => ({ name, url: `https://${name.toLowerCase()}.example/`, free, reason: `${name} reason` });
    jest.spyOn(PlatformRecommender, 'recommend').mockReturnValue({
      kind: 'fullstack', size: 'small',
      primary: pick('Alpha', true), alternatives: [pick('Beta', false), pick('Gamma', true)],
      split: { recommended: true, reason: 'Different needs', frontend: pick('Front', true), backend: pick('Back', false) },
      notes: ['note <one>'],
    } as never);
    const html = HtmlReporter.render(report());
    expect(html).toContain('small fullstack app');
    expect(html).toContain('Alpha');
    expect(html).toContain('<span class="free">free</span>');
    expect(html).toContain('Alternatives:');
    expect(html).toContain('Beta');
    expect(html).toContain('Split recommended:');
    expect(html).toContain('frontend →');
    expect(html).toContain('backend →');
    expect(html).toContain('note &lt;one&gt;');
    expect(html).toContain('rel="noopener noreferrer"');
  });

  it('omits alternatives, split and notes when the recommender returns none', () => {
    const p = { name: 'Solo', url: 'https://solo.example/', free: false, reason: 'only one' };
    jest.spyOn(PlatformRecommender, 'recommend').mockReturnValue({
      kind: 'backend', size: 'large', primary: p, alternatives: [], split: { recommended: false, reason: '' }, notes: [],
    } as never);
    const html = HtmlReporter.render(report());
    expect(html).toContain('Solo');
    expect(html).not.toContain('Alternatives:');
    expect(html).not.toContain('Split recommended');
    expect(html).not.toContain('class="notes"');
    expect(html).not.toContain('class="free"');
  });

  it('escapes a hostile platform url returned by the recommender', () => {
    const p = { name: 'X', url: 'https://x.example/"onmouseover="1', free: false, reason: 'r' };
    jest.spyOn(PlatformRecommender, 'recommend').mockReturnValue({
      kind: 'backend', size: 'small', primary: p, alternatives: [], split: { recommended: false, reason: '' }, notes: [],
    } as never);
    const html = HtmlReporter.render(report());
    expect(html).not.toContain('"onmouseover="1');
    expect(html).toContain('&quot;onmouseover=&quot;1');
  });
});

describe('FixWalker.guidanceFor', () => {
  it('uses endpoint, then file:line, then file, then "project" as the location', () => {
    expect(FixWalker.guidanceFor(f({ endpoint: 'POST /x' }))).toBe('Fix for "A finding" (POST /x):\ndo the fix');
    expect(FixWalker.guidanceFor(f())).toContain('(src/a.js:7)');
    expect(FixWalker.guidanceFor(f({ line: undefined }))).toContain('(src/a.js)');
    expect(FixWalker.guidanceFor(f({ file: undefined, line: undefined }))).toContain('(project)');
  });
});
